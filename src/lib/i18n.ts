const dicts: Record<string, Dict> = { "zh-CN": zh, en };
let current: Dict = zh;
let locale = "zh-CN";
const listeners = new Set<() => void>();
const subscribe = (listener: () => void) => {
  listeners.add(listener);
  return () => void listeners.delete(listener);
};

/** Subscribe at the app root and in memoized translated components. */
export function useLocale() {
  return useSyncExternalStore(subscribe, () => locale);
}

export function setLocale(requested: string) {
  const next = requested === "en" ? "en" : "zh-CN";
  current = dicts[next];
  document.documentElement.lang = next;
  if (next !== locale) {
    locale = next;
    listeners.forEach((listener) => listener());
  }
}

export function t(key: string, params?: Record<string, string | number | undefined>): string {
  let s = current[key] ?? (zh as Dict)[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(v === undefined ? "" : String(v));
  }
  return s;
}

export const has = (key: string) => key in current || key in zh;

export function presetName(preset: { id: string; name: string; builtin: boolean }) {
  const key = `preset.${preset.id}`;
  return preset.builtin && has(key) ? t(key) : preset.name;
}

/** Text for a backend notice (issue/warning/error) by family prefix. */
export function notice(prefix: "issue" | "warn" | "err" | "fix", n: { code: string; params?: Record<string, string> }) {
  const key = `${prefix}.${n.code}`;
  if (prefix === "err" && n.code === "verifyFailed" && n.params?.checks) {
    return t(key, { ...n.params, checks: n.params.checks.split(",").map((name) => checkName(name.trim())).join(t("common.listSeparator")) });
  }
  return has(key) ? t(key, n.params) : n.code;
}

/** "streamCopy:2" → "轨道 2 数据哈希" */
export function checkName(name: string) {
  const [base, n] = name.split(":");
  const key = `check.${base}`;
  return has(key) ? t(key, { n }) : name;
}

/** Verification text is persisted with jobs, including older Chinese diagnostics. */
export function checkValue(value: string) {
  const fixed = ["nonEmpty", "missing", "recognized", "noVideo", "hashes", "decode"];
  for (const name of fixed) {
    const key = `checkValue.${name}` as keyof typeof zh;
    if (value === zh[key] || value === en[key]) return t(key);
  }
  let match = /^(\d+) 帧全部一致$/.exec(value);
  if (match) return t("checkValue.identical", { n: match[1] });
  match = /^帧数不同：(\d+) vs (\d+)$/.exec(value);
  if (match) return t("checkValue.frameCount", { a: match[1], b: match[2] });
  match = /^第 (\d+) 帧起不一致$/.exec(value);
  return match ? t("checkValue.differ", { n: match[1] }) : value;
}
